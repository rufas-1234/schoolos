"use client";

import { useActionState } from "react";
import { importStudentsFromCsv } from "./import-actions";

const initialState: Awaited<ReturnType<typeof importStudentsFromCsv>> = {};

export function StudentImportForm() {
  const [state, formAction, pending] = useActionState(importStudentsFromCsv, initialState);

  return (
    <div className="space-y-5">
      <div className="space-y-2 text-sm leading-6 text-slate-600">
        <p>
          Upload the student CSV template. Each valid row creates a student admission for review;
          admission and roll numbers are generated by SchoolOS.
        </p>
        <p>
          Use active branch codes and exact academic year, class, and category names. Section labels
          can include or omit the &quot;Section&quot; prefix (for example, &quot;Section A&quot; or &quot;A&quot;).
          Dates must use YYYY-MM-DD. Gender values: female, male, other, non_binary, or prefer_not_to_say.
          Imports are limited to 100 rows per file and cannot attach photos or documents. If your school
          requires those uploads, add the affected students individually.
        </p>
        <a
          href="/templates/student-import-template.csv"
          download
          className="inline-flex font-semibold text-violet-700 underline underline-offset-2"
        >
          Download student CSV template
        </a>
      </div>

      <form action={formAction} className="space-y-4">
        <label className="block space-y-2 text-sm font-medium text-slate-700">
          Student CSV file
          <input
            type="file"
            name="csvFile"
            accept=".csv,text/csv"
            required
            className="block w-full rounded-xl border border-slate-200 bg-white px-3 py-2 text-sm file:mr-3 file:rounded-lg file:border-0 file:bg-violet-50 file:px-3 file:py-2 file:font-semibold file:text-violet-800"
          />
        </label>
        <button
          type="submit"
          disabled={pending}
          className="rounded-xl bg-violet-700 px-4 py-2.5 text-sm font-semibold text-white transition hover:bg-violet-800 disabled:cursor-not-allowed disabled:opacity-60"
        >
          {pending ? "Importing students..." : "Import students"}
        </button>
      </form>

      {state.error && (
        <p role="alert" className="rounded-xl border border-rose-200 bg-rose-50 px-4 py-3 text-sm text-rose-800">
          {state.error}
        </p>
      )}
      {state.completed !== undefined && (
        <div
          role={state.failures?.length ? "alert" : "status"}
          className={`rounded-xl border px-4 py-3 text-sm ${
            state.failures?.length
              ? "border-amber-200 bg-amber-50 text-amber-900"
              : "border-emerald-200 bg-emerald-50 text-emerald-900"
          }`}
        >
          <p>
            Imported {state.completed} of {state.total} student{state.total === 1 ? "" : "s"}.
          </p>
          {!!state.failures?.length && (
            <ul className="mt-2 list-inside list-disc space-y-1">
              {state.failures.map((failure) => (
                <li key={`${failure.row}-${failure.message}`}>
                  Row {failure.row}: {failure.message}
                </li>
              ))}
            </ul>
          )}
          {!!state.omittedFailures && (
            <p className="mt-2">{state.omittedFailures} additional row errors were omitted.</p>
          )}
        </div>
      )}
    </div>
  );
}
